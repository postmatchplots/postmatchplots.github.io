"""Rebuilds feed.xml, sitemap.xml and the homepage post list from the post pages.

Run automatically by .github/workflows/update-site.yml on every push.
A page counts as a post if it has <meta property="og:type" content="article">.
Each post should also carry these tags in its <head>:
  <meta property="og:title" content="The question the post answers">
  <meta property="og:description" content="Longer description for feeds and sharing">
  <meta property="article:published_time" content="2026-11-25">
  <meta name="pmp:series" content="Series name">   (optional)
  <meta name="pmp:part" content="1">                (optional, order within the series)
  <meta name="pmp:summary" content="One-line answer for the homepage list">
"""
import html
import pathlib
import re
from datetime import datetime, timezone
from email.utils import format_datetime

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE = "https://postmatchplots.github.io/"


def meta(text, key):
    m = re.search(r'<meta\s+(?:property|name)="' + re.escape(key) + r'"\s+content="([^"]*)"', text)
    return html.unescape(m.group(1)) if m else ""


def load_posts():
    posts = []
    for path in sorted(ROOT.glob("*.html")):
        text = path.read_text(encoding="utf-8")
        if meta(text, "og:type") != "article":
            continue
        date = meta(text, "article:published_time") or "1970-01-01"
        posts.append({
            "file": path.name,
            "title": meta(text, "og:title"),
            "desc": meta(text, "og:description"),
            "summary": meta(text, "pmp:summary") or meta(text, "og:description"),
            "series": meta(text, "pmp:series"),
            "part": int(meta(text, "pmp:part") or 0),
            "date": datetime.strptime(date[:10], "%Y-%m-%d").replace(hour=12, tzinfo=timezone.utc),
        })
    # Newest first; within a day, later parts first
    posts.sort(key=lambda p: (p["date"], p["part"]), reverse=True)
    return posts


def write_feed(posts):
    e = html.escape
    items = "".join(f"""
  <item>
    <title>{e(p['title'])}</title>
    <link>{BASE}{p['file']}</link>
    <guid isPermaLink="true">{BASE}{p['file']}</guid>
    <pubDate>{format_datetime(p['date'])}</pubDate>
    <description>{e(p['desc'])}</description>
  </item>""" for p in posts)
    built = format_datetime(posts[0]["date"]) if posts else format_datetime(datetime.now(timezone.utc))
    (ROOT / "feed.xml").write_text(f"""<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
<channel>
  <title>Post-Match Plots</title>
  <link>{BASE}</link>
  <atom:link href="{BASE}feed.xml" rel="self" type="application/rss+xml"/>
  <description>Football, drawn with data. One question at a time, answered with charts.</description>
  <language>en-gb</language>
  <lastBuildDate>{built}</lastBuildDate>{items}
</channel>
</rss>
""", encoding="utf-8")


def write_sitemap(posts):
    newest = posts[0]["date"].strftime("%Y-%m-%d") if posts else ""
    urls = [(BASE, newest)] + [(BASE + p["file"], p["date"].strftime("%Y-%m-%d")) for p in posts]
    body = "".join(f"  <url><loc>{u}</loc><lastmod>{d}</lastmod></url>\n" for u, d in urls)
    (ROOT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + body + "</urlset>\n", encoding="utf-8")


def write_homepage(posts):
    e = html.escape
    groups = {}
    for p in posts:  # already newest first, so groups come out newest first
        groups.setdefault(p["series"] or "More posts", []).append(p)
    blocks = []
    for name, items in groups.items():
        items = sorted(items, key=lambda p: p["part"]) if name != "More posts" else items
        month = max(p["date"] for p in items).strftime("%B %Y")
        rows = "".join(
            f'\n    <li><a href="{p["file"]}"><span class="q">{e(p["title"])}</span>'
            f'<span class="a">{e(p["summary"])}</span></a></li>' for p in items)
        blocks.append(f'  <h3 class="mute" style="font-size:20px;margin:28px 0 0">{e(name)} <span style="font-weight:500">&nbsp;/&nbsp; {month}</span></h3>\n'
                      f'  <ol class="list">{rows}\n  </ol>')
    generated = "<!-- posts:start (generated by scripts/update_site.py, edits here are overwritten) -->\n  <h2>Posts</h2>\n" + "\n".join(blocks) + "\n  <!-- posts:end -->"
    index = ROOT / "index.html"
    text = index.read_text(encoding="utf-8")
    new = re.sub(r"<!-- posts:start.*?<!-- posts:end -->", lambda m: generated, text, flags=re.S)
    if new == text and "<!-- posts:start" not in text:
        raise SystemExit("index.html has no <!-- posts:start --> ... <!-- posts:end --> markers")
    index.write_text(new, encoding="utf-8")


if __name__ == "__main__":
    posts = load_posts()
    write_feed(posts)
    write_sitemap(posts)
    write_homepage(posts)
    print(f"Updated feed, sitemap and homepage with {len(posts)} posts")
